/** Used exclusively with static option tables, never a campaign draft or API payload. */
export function translateAdsUiChoices<T>(source: T, i18nT: AdsUiTranslator): T {
  if (typeof source === "string") return adsUiText(i18nT, source) as T;
  if (Array.isArray(source)) return source.map(value => translateAdsUiChoices(value, i18nT)) as T;
  if (source && typeof source === "object") return Object.fromEntries(Object.entries(source).map(([key, value]) => [key, translateAdsUiChoices(value, i18nT)])) as T;
  return source;
}
