const ADS_UI_MATCHERS = ADS_UI_TEMPLATES.map(template => {
  const names: string[] = [];
  const chunks = template.split(/(\{value\d+\})/g);
  const expression = chunks.map(chunk => {
    if (/^\{value\d+\}$/.test(chunk)) { names.push(chunk.slice(1, -1)); return "([\\s\\S]*?)"; }
    return chunk.replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replace(/\s+/g, "\\s+");
  }).join("");
  return { template, names, pattern: new RegExp("^" + expression + "$", "u") };
});

