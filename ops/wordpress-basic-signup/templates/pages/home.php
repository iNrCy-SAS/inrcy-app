const autonomy =
document.getElementById(
'inrcyAutonomy'
);
if(!autonomy) return;
const pointsWrap =
autonomy.querySelector(
'.ia-hero-points'
);
if(!pointsWrap) return;
const points =
Array.from(
pointsWrap.querySelectorAll(
':scope > span'
)
);
if(!points.length) return;
/* Évite un double lancement Elementor */
if(
pointsWrap.dataset.heroPointsAnimated ===
'true'
){
return;
}
pointsWrap.dataset.heroPointsAnimated =
'true';
let current = -1;
let interval = null;
let started = false;
/* =========================================================
ACTIVE UN ENCADRÉ
========================================================= */
function activateNextPoint(){
points.forEach(
point => {
point.classList.remove(
'ia-hero-point-active'
);
}
);
current++;
if(
current >= points.length
){
current = 0;
}
points[current]
?.classList.add(
'ia-hero-point-active'
);
}
/* =========================================================
LANCEMENT
========================================================= */
function startSequence(){
if(started) return;
started = true;
activateNextPoint();
interval =
window.setInterval(
activateNextPoint,
1150
);
}
/* =========================================================
PAUSE
========================================================= */
function stopSequence(){
if(interval){
window.clearInterval(
interval
);
interval = null;
}
started = false;
}
/* =========================================================
LANCE UNIQUEMENT QUAND LE PREMIER BLOC EST VISIBLE
========================================================= */
if(
'IntersectionObserver'
in window
){
const observer =
new IntersectionObserver(
entries => {
const visible =
entries[0]
?.isIntersecting;
if(visible){
/*
* Petit délai pour laisser
* le titre et le texte se poser.
*/
window.setTimeout(
startSequence,
350
);
}
else{
stopSequence();
points.forEach(
point => {
point.classList.remove(
'ia-hero-point-active'
);
}
);
}
},
{
threshold:.25
}
);
observer.observe(
pointsWrap
);
}
else{
startSequence();
}
})();
</script>
